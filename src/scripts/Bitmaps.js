function bakeBitmaps(pixels, palettes, dest) {
	for (let k = 0; k < pixels.length; k++) {
		const pix = pixels[k];
		const w = pix[0].length;
		const h = pix.length;
		const c = document.createElement("canvas");
		c.width = w;
		c.height = h;
		const ctx = c.getContext("2d");
		const pal = palettes[k];
		for (let y = 0; y < h; y++) {
			for (let x = 0; x < w; x++) {
				const p = pix[y][x];
				if (p) {
					ctx.fillStyle = "#" + pal[p];
					ctx.fillRect(x, y, 1, 1);
				}
			}
		}
		dest.push(c);
	}
}

